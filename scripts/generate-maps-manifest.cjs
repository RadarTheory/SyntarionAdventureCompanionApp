const fs = require('fs');
const path = require('path');

// Maps live in public/, so Vite never sees them in its module graph and they
// can't be found with import.meta.glob. Instead we scan the folder and emit a
// small JS module that MapPanel imports synchronously — which keeps
// `import { LOCATIONS }` working everywhere without turning it into a fetch.
//
// Run automatically from vite.config.js: once on build, once on dev start, and
// again whenever a file appears in or disappears from public/Maps.

const MAPS_DIR = path.join(__dirname, '..', 'public', 'Maps');
const OUT_FILE = path.join(__dirname, '..', 'src', 'mapsGenerated.js');
const IMAGE_RE = /\.(png|jpe?g|webp|gif|avif)$/i;
// Files still carrying a raw upload id aren't maps anyone chose to name — they'd
// just clutter the picker.
const BARE_UUID_RE = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;

function humanize(filename) {
  return filename
    .replace(IMAGE_RE, '')
    .replace(/[_-]+/g, ' ')
    .replace(/([a-z0-9])([A-Z])/g, '$1 $2')   // camelCase → camel Case
    .replace(/([A-Z]+)([A-Z][a-z])/g, '$1 $2') // ABCWord → ABC Word
    .replace(/\s+/g, ' ')
    .trim();
}

function slugify(value) {
  return value.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '');
}

function generate() {
  let files = [];
  try {
    files = fs.readdirSync(MAPS_DIR).filter(f => IMAGE_RE.test(f));
  } catch {
    files = []; // folder missing — emit an empty list rather than break the build
  }

  const entries = files
    .filter(f => !BARE_UUID_RE.test(f.replace(IMAGE_RE, '')))
    .sort((a, b) => a.localeCompare(b))
    .map(filename => {
      const name = humanize(filename);
      return { id: slugify(name) || slugify(filename), name, filename };
    });

  const body =
    '// AUTO-GENERATED by scripts/generate-maps-manifest.cjs — do not edit by hand.\n' +
    '// Regenerated on build, on dev start, and whenever public/Maps changes.\n' +
    '// This is only "what is on disk"; hand-written display names live in the\n' +
    "// curated list in MapPanel.jsx, which takes precedence over anything here.\n" +
    `export const GENERATED_MAPS = ${JSON.stringify(entries, null, 2)};\n`;

  // Only write on a real change, or the dev watcher would retrigger itself.
  let previous = '';
  try { previous = fs.readFileSync(OUT_FILE, 'utf8'); } catch { /* first run */ }
  if (previous === body) return { changed: false, count: entries.length };
  fs.writeFileSync(OUT_FILE, body, 'utf8');
  return { changed: true, count: entries.length };
}

module.exports = { generate, MAPS_DIR };

if (require.main === module) {
  const { changed, count } = generate();
  console.log(`maps manifest: ${count} map(s) — ${changed ? 'written' : 'unchanged'}`);
}
