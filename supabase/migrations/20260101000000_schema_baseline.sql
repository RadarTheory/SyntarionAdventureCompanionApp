CREATE OR REPLACE FUNCTION public.oracle_match_chunks(query_embedding vector, match_count integer DEFAULT 8)
 RETURNS TABLE(chunk_id uuid, document_id uuid, content text, similarity double precision, title text, authority oracle_authority, scope oracle_scope)
 LANGUAGE sql
 STABLE
AS $function$
  select
    c.id as chunk_id,
    c.document_id,
    c.content,
    1 - (e.embedding <=> query_embedding) as similarity,
    d.title,
    d.authority,
    d.scope
  from public.oracle_embeddings e
  join public.oracle_chunks c on c.id = e.chunk_id
  join public.oracle_documents d on d.id = c.document_id
  order by e.embedding <=> query_embedding
  limit match_count;
$function$
;

