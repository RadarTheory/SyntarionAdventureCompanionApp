CREATE OR REPLACE FUNCTION public.create_module(p_name text, p_description text, p_password text)
 RETURNS bigint
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public', 'extensions'
AS $function$
declare new_id bigint;
begin
  if auth.uid() is null then raise exception 'Not signed in.'; end if;
  if length(trim(p_name)) < 2 then raise exception 'Module name too short.'; end if;
  if length(p_password) < 6 then raise exception 'Sigil must be at least 6 characters.'; end if;
  insert into modules (name, description, owner_id, dm_pass_hash)
  values (trim(p_name), p_description, auth.uid(), crypt(p_password, gen_salt('bf')))
  returning id into new_id;
  return new_id;
end;
$function$
;

