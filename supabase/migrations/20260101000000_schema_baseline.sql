CREATE OR REPLACE FUNCTION public.syntarion_ap_for_level(p_level integer)
 RETURNS integer
 LANGUAGE sql
 IMMUTABLE
AS $function$
  select case
    when p_level is null or p_level <= 1 then 0
    when p_level >= 50 then 100 * 49 * 49
    else 100 * (p_level - 1) * (p_level - 1)
  end;
$function$
;

CREATE OR REPLACE FUNCTION public.syntarion_level_for_ap(p_ap integer)
 RETURNS integer
 LANGUAGE plpgsql
 IMMUTABLE
AS $function$
declare
  v_ap integer := greatest(0, coalesce(p_ap, 0));
  v_level integer := 1;
  v_next integer;
begin
  for v_next in 2..50 loop
    exit when v_ap < public.syntarion_ap_for_level(v_next);
    v_level := v_next;
  end loop;
  return v_level;
end;
$function$
;

CREATE OR REPLACE FUNCTION public.verify_adminspace_secret(p_setting_key text, p_password text)
 RETURNS boolean
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public', 'extensions'
AS $function$
declare
  stored_hash text;
begin
  if coalesce(length(p_password), 0) = 0 then
    return false;
  end if;

  select setting_value ->> 'password_hash'
    into stored_hash
  from public.adminspace_settings
  where setting_key = p_setting_key
    and is_secret = true;

  if stored_hash is null then
    return false;
  end if;

  return stored_hash = crypt(p_password, stored_hash);
end;
$function$
;

